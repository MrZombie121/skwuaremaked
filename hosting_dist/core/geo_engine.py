def haversine_distance_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Computes great-circle distance between two GPS coordinates in kilometers."""
    r = 6371.0
    d_lat = math.radians(lat2 - lat1)
    d_lon = math.radians(lon2 - lon1)
    a = (math.sin(d_lat / 2.0) ** 2 +
         math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) *
         math.sin(d_lon / 2.0) ** 2)
    c = 2.0 * math.atan2(math.sqrt(a), math.sqrt(max(0.0, 1.0 - a)))
    return r * c

def compute_spherical_bearing(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    """Computes initial compass bearing from (lat1, lon1) towards (lat2, lon2) in degrees [0..360)."""
    rad_lat1 = math.radians(lat1)
    rad_lat2 = math.radians(lat2)
    d_lon = math.radians(lon2 - lon1)
    y = math.sin(d_lon) * math.cos(rad_lat2)
    x = math.cos(rad_lat1) * math.sin(rad_lat2) - math.sin(rad_lat1) * math.cos(rad_lat2) * math.cos(d_lon)
    return (math.degrees(math.atan2(y, x)) + 360.0) % 360.0

def calculate_projected_point(lat: float, lon: float, bearing_deg: float, distance_km: float = 25.0) -> Tuple[float, float]:
    """Projects a forward GPS point given a starting location, bearing and distance."""
    r = 6371.0
    d = distance_km / r
    rad_bearing = math.radians(bearing_deg)
    rad_lat = math.radians(lat)
    rad_lon = math.radians(lon)

    lat2 = math.asin(
        math.sin(rad_lat) * math.cos(d) +
        math.cos(rad_lat) * math.sin(d) * math.cos(rad_bearing)
    )
    lon2 = rad_lon + math.atan2(
        math.sin(rad_bearing) * math.sin(d) * math.cos(rad_lat),
        math.cos(d) - math.sin(rad_lat) * math.sin(lat2)
    )
    return math.degrees(lat2), math.degrees(lon2)

def generate_hazard_cone_polygon(lat: float, lon: float, bearing_deg: float, distance_km: float = 35.0, half_angle_deg: float = 20.0) -> List[List[float]]:
    """
    Generates a triangular / fan polygon representing the projected threat danger sector.
    Returns: List of [lat, lon] points.
    """
    left_bearing = (bearing_deg - half_angle_deg + 360.0) % 360.0
    right_bearing = (bearing_deg + half_angle_deg + 360.0) % 360.0
    
    # 5 points arc
    points = [[lat, lon]]
    for f in [0.0, 0.5, 1.0]:
        b = (left_bearing + f * (half_angle_deg * 2.0)) % 360.0
        p_lat, p_lon = calculate_projected_point(lat, lon, b, distance_km)
        points.append([round(p_lat, 4), round(p_lon, 4)])
    points.append([lat, lon])
    return points

