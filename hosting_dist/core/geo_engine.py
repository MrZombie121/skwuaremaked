def find_all_locations_in_text(text: str) -> List[Tuple[str, int, Dict[str, Any]]]:
    """Finds all occurrences of Ukrainian cities and tactical settlements in the text with start index."""
    text_clean = text.lower()
    matches = []
    occupied_spans = []

    sorted_keys = sorted(
        UKRAINE_GEO_DB.keys(),
        key=lambda k: (1 if UKRAINE_GEO_DB[k]["type"] == "region" else 0, -len(k))
    )

    for loc in sorted_keys:
        info = UKRAINE_GEO_DB[loc]
        
        if len(loc) <= 3:
            loc_pattern = r'(?:\b|[\s\.,\-_/!?:;()\[\]«»"\'/])' + re.escape(loc) + r'(?:\b|[\s\.,\-_/0-9!?:;()\[\]«»"\'/]|$)'
        elif len(loc) <= 5:
            stem = loc.rstrip('ьяюіеуаи')
            loc_pattern = r'(?:\b|[\s\.,\-_/!?:;()\[\]«»"\'/])' + re.escape(stem) + r'[а-яіїєґa-z\-]{0,4}(?:\b|[\s\.,\-_/0-9!?:;()\[\]«»"\'/]|$)'
        else:
            stem = loc.rstrip('ьяюіеуаи')
            if len(stem) > 6:
                stem = stem[:6]
            loc_pattern = r'(?:\b|[\s\.,\-_/!?:;()\[\]«»"\'/])' + re.escape(stem) + r'[а-яіїєґa-z\-]{0,10}(?:\b|[\s\.,\-_/0-9]|$)'

        for m in re.finditer(loc_pattern, text_clean):
            start, end = m.start(), m.end()
            if any(s <= start < e or s < end <= e for s, e in occupied_spans):
                continue

            occupied_spans.append((start, end))
            matches.append((loc, start, info))

    matches.sort(key=lambda x: x[1])
    return matches

def extract_current_and_destination(text: str) -> Tuple[Optional[Tuple[str, float, float, str]], Optional[Tuple[str, float, float, str]]]:
    """
    Parses spatial movement semantics:
    e.g. '2х шахеда повз Очаків курсом на Вознесенськ' -> (Очаків, Вознесенськ)
    e.g. 'з Моря до Овідіополю' -> (Чорне море, Овідіополь)
    e.g. 'БпЛА руслом на Розумівку' -> (Запоріжжя/Русло, Розумівка)
    """
    matches = find_all_locations_in_text(text)
    if not matches:
        return None, None

    text_lower = text.lower()
    dest_match = re.search(r'(?:курсом\s+на|в\s+бік|у\s+бік|в\s+напрямку|напрямок\s+|вектор\s+на|до\s+|на\s+|в\s+|у\s+)([а-яіїєґa-z\-]+)', text_lower)
    passing_match = re.search(r'(?:повз|мимо|через|в\s+районі|над|біля|поблизу|транзитом\s+через|з\s+району|з\s+боку|з\s+моря|з\s+чорного\s+моря|зі\s+сходу|з\s+півдня|з\s+півночі|з\s+акваторії)\s*([а-яіїєґa-z\-]*)', text_lower)

    if len(matches) == 1:
        loc_key, match_idx, info = matches[0]
        if dest_match and match_idx >= dest_match.start():
            dest_tuple = (loc_key.title(), info["lat"], info["lon"], info["region"])
            return dest_tuple, dest_tuple
        else:
            return (loc_key.title(), info["lat"], info["lon"], info["region"]), None

    dest_info = None
    passing_info = None

    if passing_match and dest_match:
        pass_idx = passing_match.start()
        dest_idx = dest_match.start()
        
        pass_candidates = [m for m in matches if m[1] >= pass_idx and (dest_idx < pass_idx or m[1] < dest_idx)]
        dest_candidates = [m for m in matches if m[1] >= dest_idx and (pass_idx < dest_idx or m[1] < pass_idx)]
        
        if pass_candidates:
            p_loc, _, p_data = pass_candidates[0]
            passing_info = (p_loc.title(), p_data["lat"], p_data["lon"], p_data["region"])
        
        if dest_candidates:
            d_loc, _, d_data = dest_candidates[0]
            dest_info = (d_loc.title(), d_data["lat"], d_data["lon"], d_data["region"])

    if not passing_info or not dest_info:
        if dest_match:
            dest_idx = dest_match.start()
            dest_cand = [m for m in matches if m[1] >= dest_idx]
            curr_cand = [m for m in matches if m[1] < dest_idx]

            if dest_cand:
                d_loc, _, d_data = dest_cand[0]
                dest_info = (d_loc.title(), d_data["lat"], d_data["lon"], d_data["region"])
            if curr_cand:
                p_loc, _, p_data = curr_cand[0]
                passing_info = (p_loc.title(), p_data["lat"], p_data["lon"], p_data["region"])
            elif len(matches) > 1:
                other_cand = [m for m in matches if m[0] != dest_info[0].lower()]
                if other_cand:
                    p_loc, _, p_data = other_cand[0]
                    passing_info = (p_loc.title(), p_data["lat"], p_data["lon"], p_data["region"])
        else:
            p_loc, _, p_data = matches[0]
            passing_info = (p_loc.title(), p_data["lat"], p_data["lon"], p_data["region"])
            d_loc, _, d_data = matches[1]
            dest_info = (d_loc.title(), d_data["lat"], d_data["lon"], d_data["region"])

    return passing_info, dest_info

def lookup_location(text: str) -> Optional[Tuple[str, float, float, str]]:
    curr, _ = extract_current_and_destination(text)
    return curr
